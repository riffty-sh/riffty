use serde::{Deserialize, Serialize};

const VENDORED_DIR_SEGMENTS: &[&str] = &[
    "vendor",
    "vendored",
    "third_party",
    "third-party",
    "node_modules",
    "dist",
    "build",
    "generated",
    "__generated__",
    "gen-py",
    "gen-java",
    "gen-js",
];

const GENERATED_FILENAME_SUFFIXES: &[&str] = &[
    ".min.js",
    ".min.mjs",
    ".min.cjs",
    ".pb.py",
    ".pb.ts",
    ".pb.js",
    "_pb2.py",
    "_pb2_grpc.py",
    ".generated.ts",
    ".generated.js",
    ".generated.py",
    ".generated.java",
    ".g.ts",
    ".d.ts",
];

const GENERATED_HEADER_MARKERS: &[&str] = &[
    "@generated",
    "do not edit",
    "code generated by",
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "@ts-nocheck",
];

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct VendoredMatch {
    pub path: String,
    pub reason: String,
}

/// Inspects a repo-relative file path and optional file contents (first 25 lines)
/// to determine whether the file is vendored or machine-generated.
pub fn classify_vendored_or_generated(
    relative_path: &str,
    content: Option<&str>,
) -> Option<VendoredMatch> {
    let normalized = relative_path.replace('\\', "/");
    let lower_path = normalized.to_ascii_lowercase();

    for segment in lower_path.split('/') {
        if VENDORED_DIR_SEGMENTS.contains(&segment) {
            return Some(VendoredMatch {
                path: normalized,
                reason: format!("vendored/generated directory segment '{segment}/'"),
            });
        }
    }

    for suffix in GENERATED_FILENAME_SUFFIXES {
        if lower_path.ends_with(suffix) {
            return Some(VendoredMatch {
                path: normalized,
                reason: format!("generated/minified filename suffix '{suffix}'"),
            });
        }
    }

    if let Some(text) = content {
        for (idx, line) in text.lines().take(25).enumerate() {
            let lower_line = line.to_ascii_lowercase();
            for marker in GENERATED_HEADER_MARKERS {
                if lower_line.contains(marker) {
                    return Some(VendoredMatch {
                        path: normalized,
                        reason: format!("header marker '{marker}' on line {}", idx + 1),
                    });
                }
            }
        }
    }

    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn flags_vendored_directories_and_minified_files() {
        assert!(classify_vendored_or_generated("vendor/pkg/foo.py", None).is_some());
        assert!(classify_vendored_or_generated("src/third_party/lib.ts", None).is_some());
        assert!(classify_vendored_or_generated("web/node_modules/a/index.js", None).is_some());
        assert!(classify_vendored_or_generated("dist/bundle.min.js", None).is_some());
        assert!(classify_vendored_or_generated("proto/service_pb2.py", None).is_some());
    }

    #[test]
    fn flags_generated_header_markers_in_first_25_lines() {
        let generated_ts = "// @generated by openapi-generator\n// DO NOT EDIT\nexport const x = 1;\n";
        let m = classify_vendored_or_generated("src/api/client.ts", Some(generated_ts))
            .expect("should flag @generated header");
        assert!(m.reason.contains("@generated"));

        let nocheck = "// @ts-nocheck\nexport function foo() {}\n";
        let m2 = classify_vendored_or_generated("src/legacy.ts", Some(nocheck))
            .expect("should flag @ts-nocheck");
        assert!(m2.reason.contains("@ts-nocheck"));
    }

    #[test]
    fn does_not_flag_normal_source_files() {
        let normal_py = "from datetime import datetime\n\ndef now_utc():\n    return datetime.utcnow()\n";
        assert!(classify_vendored_or_generated("src/app/time_utils.py", Some(normal_py)).is_none());
        assert!(
            classify_vendored_or_generated(
                "libs/langchain-core/src/utils/fast-json-patch/src/helpers.ts",
                Some("export function deepClone(obj: unknown) { return JSON.parse(JSON.stringify(obj)); }\n")
            )
            .is_none()
        );
    }
}
